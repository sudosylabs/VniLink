/**
 * Keeps the licensing of the source in one state: a file written here carries the project's notice, a file copied from
 * VS Code keeps VS Code's, and one copied and changed carries both. The provenance
 * manifest decides which files were copied; a copy that is not in it is recognised
 * by the notice it already carries.
 */
import { execFile } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { promisify } from 'node:util';
import { recordAdaptations } from '../vscodeImport.ts';
import { commentStyleOf, leadingMicrosoftNotice, modificationNotice, originalNotice, renderNotice, type CommentStyle } from './licenseNotice.ts';
import { readProduct } from './product.ts';

const run = promisify(execFile);

/** Third-party sources keep their own license and notice. */
const excludedDirectories = ['vendor/'];

/** Copied VS Code files that are not in the provenance manifest. */
const verbatimDirectories = ['build/lint/vscode/'];

/**
 * - `original`: written for this project.
 * - `verbatim`: VS Code's or another project's text, byte for byte; its notice stays as it is.
 * - `derived`: copied from VS Code and changed here.
 */
export type NoticeKind = 'original' | 'verbatim' | 'derived';

export interface LicenseFinding {
	readonly path: string;
	readonly message: string;
}

interface ManifestEntry {
	readonly path: string;
	readonly adapted?: boolean;
}

/** The path of the pinned VS Code copies and which of them this project changed. */
export async function readCopies(root: string): Promise<ReadonlyMap<string, ManifestEntry>> {
	const manifest = JSON.parse(await readFile(join(root, 'build', 'vscode-source.json'), 'utf8')) as { files: ManifestEntry[] };
	return new Map(manifest.files.map(file => [file.path, file]));
}

/** A generated binding is the output of its header's license, not a file written here. */
function isGenerated(text: string): boolean {
	return /generated by bindgen/i.test(text.slice(0, 600));
}

/**
 * The kind of notice `path` carries given its `text`, or `undefined` when it carries none:
 * data and markup files (covered by `REUSE.toml`), third-party sources and generated files.
 */
export function noticeKindOf(path: string, text: string, copies: ReadonlyMap<string, ManifestEntry>): NoticeKind | undefined {
	const style = commentStyleOf(path);
	if (style === undefined || excludedDirectories.some(directory => path.startsWith(directory)) || text.length === 0 || isGenerated(text)) {
		return undefined;
	}
	const copy = copies.get(path);
	if (copy) {
		return copy.adapted ? 'derived' : 'verbatim';
	}
	if (verbatimDirectories.some(directory => path.startsWith(directory))) {
		return 'verbatim';
	}
	return leadingMicrosoftNotice(text.slice(prelude(text, style).length), style) === undefined ? 'original' : 'derived';
}

/** A line before which the notice cannot go: a shebang, or the line that turns a batch file's echo off. */
function prelude(text: string, style: CommentStyle): string {
	const first = text.slice(0, text.indexOf('\n') + 1);
	return (style === 'hash' && first.startsWith('#!')) || (style === 'rem' && /^@echo off\s*$/i.test(first)) ? first : '';
}

/** `text` with the notice of `kind` in place, or `undefined` when it already is; throws what it cannot place. */
function withNotice(path: string, text: string, kind: 'original' | 'derived', holder: string): string | undefined {
	const style = commentStyleOf(path);
	if (style === undefined) {
		throw new Error('cannot carry a notice');
	}
	const head = prelude(text, style);
	const body = text.slice(head.length);
	if (kind === 'original') {
		const notice = renderNotice(style, originalNotice(holder));
		if (body.startsWith(notice)) {
			return undefined;
		}
		if (/^\s*(\/\/|\/\*|\*|#|REM)\s*(Copyright|SPDX-License-Identifier)/m.test(body.split('\n').slice(0, 12).join('\n'))) {
			throw new Error('carries a notice this project did not write');
		}
		return `${head}${notice}\n${body}`;
	}
	const microsoft = leadingMicrosoftNotice(body, style);
	if (microsoft === undefined) {
		throw new Error('is copied from VS Code but does not start with its notice');
	}
	// Stylelint wants an empty line before the second comment of a stylesheet.
	const separator = style === 'css' ? '\n' : '';
	const notice = `${separator}${renderNotice(style, modificationNotice(holder))}`;
	const current = microsoft.replace('See License.txt in the project root', 'See LICENSE.vscode.txt in the project root');
	if (body.startsWith(`${current}${notice}`)) {
		return undefined;
	}
	const rest = body.slice(microsoft.length);
	if (/^\s*(\/\/|\/\*|\*|#|REM)\s*(Modifications Copyright|SPDX-License-Identifier)/m.test(rest.split('\n').slice(0, 8).join('\n'))) {
		throw new Error('carries a modification notice this project did not write');
	}
	return `${head}${current}${notice}${rest}`;
}

/** Why `text`, the contents of `path`, does not carry the notice its kind requires; `undefined` when it does. */
export function findNoticeProblem(path: string, text: string, kind: NoticeKind, holder: string): string | undefined {
	if (kind === 'verbatim') {
		return text.includes('SPDX-License-Identifier: AGPL') ? 'is copied unchanged, so it keeps its own notice and not this project\'s' : undefined;
	}
	try {
		return withNotice(path, text, kind, holder) === undefined ? undefined : kind === 'original' ? 'has no notice' : 'has VS Code\'s notice but not the modification notice, or one that is out of date';
	} catch (error) {
		return (error as Error).message;
	}
}

// A git hook's GIT_DIR and GIT_INDEX_FILE name the repository committing, not necessarily `root`'s.
async function git(root: string, args: readonly string[]): Promise<string> {
	const env = Object.fromEntries(Object.entries(process.env).filter(([name]) => !name.startsWith('GIT_')));
	return (await run('git', ['-C', root, ...args], { env, maxBuffer: 64 * 1024 * 1024 })).stdout;
}

async function noticeFiles(root: string): Promise<{ path: string; text: string; kind: NoticeKind }[]> {
	const copies = await readCopies(root);
	const paths = (await git(root, ['ls-files', '-z', '--cached', '--others', '--exclude-standard'])).split('\0').filter(path => path.length > 0);
	const files: { path: string; text: string; kind: NoticeKind }[] = [];
	for (const path of new Set(paths)) {
		if (commentStyleOf(path) === undefined) {
			continue;
		}
		let text: string;
		try {
			text = await readFile(join(root, path), 'utf8');
		} catch (error) {
			// Deleted in the working tree but still in the index.
			if ((error as NodeJS.ErrnoException).code === 'ENOENT') {
				continue;
			}
			throw error;
		}
		const kind = noticeKindOf(path, text, copies);
		if (kind !== undefined) {
			files.push({ path, text, kind });
		}
	}
	return files;
}

/** The place in `package.json` and `Cargo.toml` where the project names its license. */
async function findMetadataProblems(root: string): Promise<LicenseFinding[]> {
	const problems: LicenseFinding[] = [];
	const text = await readFile(join(root, 'LICENSE'), 'utf8').catch(() => '');
	if (!/GNU AFFERO GENERAL PUBLIC LICENSE\s+Version 3, 19 November 2007/.test(text)) {
		problems.push({ path: 'LICENSE', message: 'is not the text of the GNU Affero General Public License, version 3' });
	}
	const manifest = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')) as { license?: string };
	if (manifest.license !== 'AGPL-3.0-only') {
		problems.push({ path: 'package.json', message: '"license" is not "AGPL-3.0-only"' });
	}
	if (!/^license = "AGPL-3\.0-only"$/m.test(await readFile(join(root, 'Cargo.toml'), 'utf8'))) {
		problems.push({ path: 'Cargo.toml', message: 'the workspace license is not "AGPL-3.0-only"' });
	}
	return problems;
}

/** Fails listing each source file without the notice its kind requires, and each place that misnames the license. */
export async function checkLicense(root: string): Promise<void> {
	const { publisherName } = await readProduct(root);
	const findings = await findMetadataProblems(root);
	const files = await noticeFiles(root);
	for (const { path, text, kind } of files) {
		const problem = findNoticeProblem(path, text, kind, publisherName);
		if (problem !== undefined) {
			findings.push({ path, message: `${kind} file ${problem}` });
		}
	}
	if (findings.length > 0) {
		throw new Error(`Licensing; see .agents/skills/licensing/SKILL.md:\n${findings.map(finding => `  ${finding.path}: ${finding.message}`).join('\n')}`);
	}
	const counts = (kind: NoticeKind) => files.filter(file => file.kind === kind).length;
	console.log(`License: ${String(counts('original'))} files carry the project's notice, ${String(counts('derived'))} carry VS Code's and the project's, ${String(counts('verbatim'))} are copied as they are.`);
}

export interface ApplyOptions {
	/** Writes the changes; without it they are only counted. */
	readonly write?: boolean;
	/** Records the new contents of adapted copies in the provenance manifest. */
	readonly record?: (paths: readonly string[]) => Promise<void>;
}

/** Adds the notice every source file needs and returns the files it changed; throws, changing nothing, if a file cannot take one. */
export async function applyLicense(root: string, options: ApplyOptions = {}): Promise<string[]> {
	const { publisherName } = await readProduct(root);
	const copies = await readCopies(root);
	const changes: { path: string; text: string }[] = [];
	const problems: LicenseFinding[] = [];
	for (const { path, text, kind } of await noticeFiles(root)) {
		if (kind === 'verbatim') {
			continue;
		}
		try {
			const updated = withNotice(path, text, kind, publisherName);
			if (updated !== undefined) {
				changes.push({ path, text: updated });
			}
		} catch (error) {
			problems.push({ path, message: `${kind} file ${(error as Error).message}` });
		}
	}
	if (problems.length > 0) {
		throw new Error(`Nothing changed; these files need a decision:\n${problems.map(problem => `  ${problem.path}: ${problem.message}`).join('\n')}`);
	}
	if (options.write) {
		for (const { path, text } of changes) {
			await writeFile(join(root, path), text);
		}
		const adapted = changes.map(change => change.path).filter(path => copies.get(path)?.adapted);
		if (adapted.length > 0) {
			await (options.record ?? recordAdaptations)(adapted);
		}
	}
	return changes.map(change => change.path);
}

/** The `license:apply` task: `--write` changes the files. */
export async function applyLicenseCommand(root: string, args: readonly string[]): Promise<void> {
	const changed = await applyLicense(root, { write: args.includes('--write') });
	console.log(`${args.includes('--write') ? 'Added a notice to' : 'Would add a notice to'} ${String(changed.length)} files.`);
}
